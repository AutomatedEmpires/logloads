#!/usr/bin/env node
// One-time local development setup: creates or completes apps/web/.env.local.
//
// - Generates local-only secrets with crypto.randomBytes; never prints them.
// - Never overwrites a value that already exists.
// - Adds no Supabase, Stripe, Clerk or other provider keys, so a fresh local
//   app uses the development JSON store and seeded sign-in, never production.
// - Refuses to run on CI/Vercel, and refuses to write a file git would track.
import { execFileSync } from "node:child_process"
import { randomBytes } from "node:crypto"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

export const LOCAL_APP_URL = "http://localhost:3002"

/** Keys this setup owns. `generate` returns the value for a missing key. */
export const LOCAL_ENV_KEYS = [
  {
    comment: "Loopback URL. Development sign-in stays off unless this is a loopback address.",
    generate: () => LOCAL_APP_URL,
    name: "NEXT_PUBLIC_APP_URL"
  },
  {
    comment: "Local-only session signing key (production uses its own secret from Doppler/Vercel).",
    generate: (random) => random(32),
    name: "LOGLOADS_SESSION_SECRET",
    secret: true
  },
  {
    comment: "Local-only HMAC key that pseudonymizes rate-limit callers (required in every environment).",
    generate: (random) => random(32),
    name: "LOGLOADS_RATE_LIMIT_HMAC_SECRET",
    secret: true
  }
]

const LOOPBACK_HOSTS = new Set(["localhost", "127.0.0.1", "::1", "[::1]"])

export function randomHex(bytes) {
  return randomBytes(bytes).toString("hex")
}

/** Parses KEY=value lines; ignores comments and blanks. Values are kept verbatim. */
export function parseEnv(text) {
  const values = new Map()

  for (const line of text.split(/\r?\n/)) {
    const match = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/.exec(line)

    if (match) {
      values.set(match[1], match[2].trim())
    }
  }

  return values
}

function isLoopbackUrl(value) {
  try {
    return LOOPBACK_HOSTS.has(new URL(value.replace(/^["']|["']$/g, "")).hostname.toLowerCase())
  } catch {
    return false
  }
}

/**
 * Pure planning step (unit-tested): given the current file text, returns the new
 * text, the key names added, and warnings. Existing non-empty values are never changed.
 */
export function planLocalEnv(existingText, random = randomHex) {
  const existing = parseEnv(existingText)
  const added = []
  const warnings = []
  const lines = []

  for (const key of LOCAL_ENV_KEYS) {
    if (existing.get(key.name)) {
      continue
    }

    if (existing.has(key.name)) {
      warnings.push(`${key.name} is present but empty; fill it in manually or delete the line and re-run.`)
      continue
    }

    lines.push(`# ${key.comment}`, `${key.name}=${key.generate(random)}`)
    added.push(key.name)
  }

  const appUrl = existing.get("NEXT_PUBLIC_APP_URL")

  if (appUrl && !isLoopbackUrl(appUrl)) {
    warnings.push("NEXT_PUBLIC_APP_URL is not a loopback URL, so seeded development sign-in will stay disabled.")
  }

  const supabaseUrl = existing.get("SUPABASE_URL")

  if (supabaseUrl && !isLoopbackUrl(supabaseUrl)) {
    warnings.push("SUPABASE_URL points at a non-local project. Local development should use the JSON store or a local Supabase stack, never production.")
  }

  let text = existingText

  if (lines.length > 0) {
    const header = existingText.trim().length === 0
      ? "# Local development only. Generated by `pnpm setup:local`. Never commit this file.\n"
      : (existingText.endsWith("\n") ? "" : "\n")
    text = `${existingText}${header}${lines.join("\n")}\n`
  }

  return { added, text, warnings }
}

export function refuseHostedRuntime(environment) {
  if (environment.CI || environment.VERCEL || environment.VERCEL_ENV || environment.VERCEL_URL) {
    throw new Error("setup:local is for a developer machine only; refusing to run on CI or Vercel.")
  }
}

function assertGitIgnored(repoRoot, target) {
  try {
    execFileSync("git", ["-C", repoRoot, "check-ignore", "-q", relative(repoRoot, target)], { stdio: "ignore" })
  } catch {
    throw new Error(`${relative(repoRoot, target)} is not ignored by git; refusing to write secrets into it.`)
  }
}

function main() {
  refuseHostedRuntime(process.env)

  const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..")
  const target = join(repoRoot, "apps", "web", ".env.local")
  assertGitIgnored(repoRoot, target)

  const before = existsSync(target) ? readFileSync(target, "utf8") : ""
  const { added, text, warnings } = planLocalEnv(before)

  if (added.length > 0) {
    writeFileSync(target, text, { encoding: "utf8", mode: 0o600 })
  }

  const where = relative(repoRoot, target).replaceAll("\\", "/")
  console.log(added.length > 0 ? `${where}: added ${added.join(", ")} (values not shown)` : `${where}: already complete, nothing changed`)

  for (const warning of warnings) {
    console.warn(`warning: ${warning}`)
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    main()
  } catch (error) {
    console.error(`setup:local: ${error.message}`)
    process.exit(1)
  }
}
